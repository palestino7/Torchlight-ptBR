def translate_item_comprehensive(s: str) -> str | None:
    """
    Translates any complex item name into idiomatic Portuguese.
    """
    # 1. Spell scroll: 'Spell: Web I' -> 'Feitiço: Teia I'
    if s.startswith("Spell: "):
        spell_name = s[len("Spell: "):].strip()
        m_roman = re.match(r"^(.*?)\s+(I|II|III|IV|V|VI|VII|VIII|IX|X)$", spell_name)
        if m_roman:
            base, num = m_roman.groups()
            base_pt = SINGLE_WORDS_DICT.get(base, base)
            return f"Feitiço: {base_pt} {num}"
        base_pt = SINGLE_WORDS_DICT.get(spell_name, spell_name)
        return f"Feitiço: {base_pt}"

    # 2. Check Epic items: 'Epic ...' or 'epic...'
    is_epic = False
    clean_s = s
    if clean_s.startswith("Epic "):
        is_epic = True
        clean_s = clean_s[5:]
    elif clean_s.startswith("epic"):
        is_epic = True
        clean_s = clean_s[4:]
        if clean_s.startswith("a "):
            clean_s = clean_s[2:]
        elif clean_s.startswith("v "):
            clean_s = clean_s[2:]

    # Check internal item naming patterns: 'ring rare 01' -> 'Anel Raro 01'
    m_int = re.match(r"^(ring|necklace|belt|boots|gloves|helm|armor|shield|sword|axe|bow|staff|wand|mace|rifle|pistol)\s+(rare|magic|unique)\s+(\w+)$", clean_s, re.I)
    if m_int:
        noun, rarity, code = m_int.groups()
        noun_info = EQUIPMENT_NOUNS.get(noun.capitalize(), (noun, "m"))
        pt_noun = noun_info[0]
        gender = noun_info[1]
        pt_rarity = "Raro" if rarity.lower() == "rare" else ("Mágico" if rarity.lower() == "magic" else "Único")
        if gender == "f":
            pt_rarity = pt_rarity.replace("o", "a")
        res = f"{pt_noun} {pt_rarity} {code}"
        if is_epic:
            epic_word = "Épica" if gender == "f" else ("Épicas" if gender == "f_p" else ("Épicos" if gender == "m_p" else "Épico"))
            res = f"{pt_noun} {pt_rarity} {epic_word} {code}"
        return res

    # Check 'Noun of Suffix'
    if " of " in clean_s:
        base_part, suffix_part = clean_s.split(" of ", 1)
        base_info = EQUIPMENT_NOUNS.get(base_part)
        pt_base = base_info[0] if base_info else base_part
        gender = base_info[1] if base_info else "m"
        full_suffix = f"of {suffix_part}"
        pt_suffix = OF_AFFIXES.get(full_suffix, f"de {suffix_part}")
        res = f"{pt_base} {pt_suffix}"
        if is_epic:
            epic_word = "Épica" if gender == "f" else ("Épicas" if gender == "f_p" else ("Épicos" if gender == "m_p" else "Épico"))
            res = f"{res} {epic_word}"
        return res

    # Check 2 words: [Modifier] [Noun]
    words = clean_s.split()
    if len(words) == 2:
        w1, w2 = words[0], words[1]
        base_info = EQUIPMENT_NOUNS.get(w2)
        if base_info and w1 in MODIFIER_ADJECTIVES:
            pt_base, gender = base_info
            pt_mod = MODIFIER_ADJECTIVES[w1]
            res = f"{pt_base} {pt_mod}"
            if is_epic:
                epic_word = "Épica" if gender == "f" else ("Épicas" if gender == "f_p" else ("Épicos" if gender == "m_p" else "Épico"))
                res = f"{res} {epic_word}"
            return res

    # Check 3 words: [Mod1] [Mod2] [Noun]
    if len(words) == 3:
        w1, w2, w3 = words[0], words[1], words[2]
        base_info = EQUIPMENT_NOUNS.get(w3)
        if base_info and w1 in MODIFIER_ADJECTIVES and w2 in MODIFIER_ADJECTIVES:
            pt_base, gender = base_info
            m1 = MODIFIER_ADJECTIVES[w1]
            m2 = MODIFIER_ADJECTIVES[w2]
            res = f"{pt_base} {m1} {m2}"
            if is_epic:
                epic_word = "Épica" if gender == "f" else ("Épicas" if gender == "f_p" else ("Épicos" if gender == "m_p" else "Épico"))
                res = f"{res} {epic_word}"
            return res

    # Single equipment noun
    if clean_s in EQUIPMENT_NOUNS:
        pt_base, gender = EQUIPMENT_NOUNS[clean_s]
        if is_epic:
            epic_word = "Épica" if gender == "f" else ("Épicas" if gender == "f_p" else ("Épicos" if gender == "m_p" else "Épico"))
            return f"{pt_base} {epic_word}"
        return pt_base

    return None

def translate_any_string(orig: str, category: str = "Globals") -> str:
    """
    Master translation function for 100% of Torchlight strings.
    """
    s = orig.strip()

    # 1. Exact match in Canonical / Reference dictionaries
    for d in (CANONICAL_UI, CANONICAL_ITEMS, CANONICAL_SKILLS, CANONICAL_QUESTS,
              CANONICAL_MONSTERS, CANONICAL_GLOBALS, EXACT_TRANSLATIONS,
              RECIPES_DICT, QUESTS_DICT, DUNGEONS_DICT, AFFIX_SPECIAL_DICT,
              MONSTERS_DICT, SKILLS_DICT, GLOBALS_DICT, SINGLE_WORDS_DICT):
        if s in d:
            return d[s]

    # 2. [Word] [ITEM] Affixes (e.g. Bold [ITEM] -> [ITEM] Audaz)
    if s.endswith(" [ITEM]"):
        adj = s[:-7].strip()
        if adj in AFFIX_ADJECTIVES:
            return f"[ITEM] {AFFIX_ADJECTIVES[adj]}"
        return f"[ITEM] {adj}"

    # 3. Item Equipment & Spells
    if category in ("Items", "Affixes", "Recipes") or any(noun in s for noun in ["Axe", "Bow", "Sword", "Shield", "Boots", "Helm", "Staff", "Wand", "Spell:"]):
        item_tr = translate_item_comprehensive(s)
        if item_tr:
            return item_tr

    # 4. Monster abilities & descriptions
    if category == "Monsters":
        mon_tr = translate_monster_fallback(s)
        if mon_tr:
            return mon_tr

    # 5. Fallback for single words
    if len(s.split()) == 1 and s in SINGLE_WORDS_DICT:
        return SINGLE_WORDS_DICT[s]

    # Return original if internal code/untranslatable
    return orig
